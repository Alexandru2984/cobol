#!/usr/bin/env python3
"""Generate the native schema constants from the same SQL used by upgrades."""
import argparse
import json
from pathlib import Path

root = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--check", action="store_true")
args = parser.parse_args()
lines = ["/* Generated by ops/generate-schema.py; edit SQL migrations instead. */\n"]
for source in sorted((root / "migrations").glob("*.sql")):
    version = int(source.name.split("_", 1)[0])
    lines.append(f"static const char ledger_schema_{version}[] =\n")
    lines.extend("    " + json.dumps(line, ensure_ascii=True) + "\n" for line in source.read_text().splitlines(keepends=True))
    lines.append("    ;\n")
content = "".join(lines)
target = root / "persistence/schema.h"
if args.check:
    if not target.exists() or target.read_text() != content:
        raise SystemExit("Native schema is stale: run python3 ops/generate-schema.py")
else:
    target.write_text(content)
